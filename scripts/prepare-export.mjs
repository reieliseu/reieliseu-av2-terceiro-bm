import { access, writeFile } from 'node:fs/promises'
import { basePath } from '../config/site.mjs'

await access(new URL('../out/index.html', import.meta.url))
await writeFile(new URL('../out/.htaccess', import.meta.url), `# Generated by pnpm build:web. Upload this hidden file too.
DirectoryIndex index.html
ErrorDocument 404 ${basePath}/404.html
<IfModule mod_headers.c>
  Header always set X-Content-Type-Options "nosniff"
  Header always set Referrer-Policy "strict-origin-when-cross-origin"
  Header always set Strict-Transport-Security "max-age=63072000"
  Header always set X-Frame-Options "SAMEORIGIN"
  Header always set Permissions-Policy "camera=(), microphone=(), geolocation=()"
</IfModule>
`)
console.log('Apache configuration generated in out/.htaccess')
